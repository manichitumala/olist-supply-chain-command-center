"""
Phase 1 - Data Quality Engineering.

Runs sql/bronze/02_data_quality_checks.sql against the bronze layer and
compiles the results into reports/data_quality_report.md, plus CSV samples
of the worst offenders for a few key checks so the report has real evidence
attached, not just counts.
"""

import re

import pandas as pd

from config import CHARTS_DIR, EXPORTS_DIR, REPORTS_DIR, ROOT
from db import get_engine

DQ_SQL_PATH = ROOT / "sql" / "bronze" / "02_data_quality_checks.sql"

SECTION_RE = re.compile(r"^\d+\.\s+[A-Z]")
ITEM_RE = re.compile(r"^\d+[a-z]\.\s")

# Extra "show me the evidence" queries: real offending rows, not just counts.
EVIDENCE_QUERIES = {
    "orders_without_customer_sample": """
        SELECT o.order_id, o.customer_id, o.order_status, o.order_purchase_timestamp
        FROM bronze.orders o
        LEFT JOIN bronze.customers c ON o.customer_id = c.customer_id
        WHERE c.customer_id IS NULL
        LIMIT 20
    """,
    "delivered_before_purchase_sample": """
        SELECT order_id, order_status, order_purchase_timestamp, order_delivered_customer_date
        FROM bronze.orders
        WHERE order_delivered_customer_date IS NOT NULL
          AND order_delivered_customer_date::timestamp < order_purchase_timestamp::timestamp
        LIMIT 20
    """,
    "carrier_before_approved_sample": """
        SELECT order_id, order_status, order_approved_at, order_delivered_carrier_date
        FROM bronze.orders
        WHERE order_delivered_carrier_date IS NOT NULL
          AND order_approved_at IS NOT NULL
          AND order_delivered_carrier_date::timestamp < order_approved_at::timestamp
        LIMIT 20
    """,
    "delivered_status_missing_delivered_date_sample": """
        SELECT order_id, order_status, order_purchase_timestamp, order_delivered_customer_date
        FROM bronze.orders
        WHERE order_status = 'delivered' AND order_delivered_customer_date IS NULL
        LIMIT 20
    """,
}


def parse_statements(sql_text: str):
    """Splits the DQ SQL file into (label, sql) pairs using the comment
    line directly above each statement as its label. Statement boundaries
    are detected from ';' at the end of an actual code line (not inside
    comments), so semicolons in prose comments are safe."""
    statements = []
    comment_lines, code_lines = [], []

    for raw_line in sql_text.split("\n"):
        stripped = raw_line.strip()
        if not code_lines and stripped.startswith("--"):
            comment_lines.append(stripped.lstrip("-").strip())
        elif not code_lines and not stripped:
            continue
        elif stripped:
            code_lines.append(raw_line)
            if stripped.endswith(";"):
                item_comments = [c for c in comment_lines if ITEM_RE.match(c)]
                if item_comments:
                    label = item_comments[0]
                else:
                    section_comments = [c for c in comment_lines if SECTION_RE.match(c)]
                    label = section_comments[-1] if section_comments else "Query"
                sql = "\n".join(code_lines).rstrip(";").strip()
                statements.append((label, sql))
                comment_lines, code_lines = [], []

    return statements


def render_result_as_markdown(df: pd.DataFrame) -> str:
    if df.shape == (1, 1):
        col = df.columns[0]
        return f"**{col}: {df.iloc[0, 0]}**"
    return df.to_markdown(index=False)


def main():
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    EXPORTS_DIR.mkdir(parents=True, exist_ok=True)
    CHARTS_DIR.mkdir(parents=True, exist_ok=True)

    engine = get_engine()
    sql_text = DQ_SQL_PATH.read_text(encoding="utf-8")
    statements = parse_statements(sql_text)

    lines = [
        "# Olist Bronze Layer - Data Quality Report",
        "",
        "Generated by `python/data_quality.py` against the `bronze` schema "
        "(raw, untyped CSV load). This is the baseline audit that the "
        "silver-layer cleaning rules are derived from.",
        "",
    ]

    with engine.connect() as conn:
        for label, sql in statements:
            df = pd.read_sql(sql, conn)
            lines.append(f"## {label}")
            lines.append("")
            lines.append(render_result_as_markdown(df))
            lines.append("")

        lines.append("## Evidence samples")
        lines.append("")
        for name, sql in EVIDENCE_QUERIES.items():
            df = pd.read_sql(sql, conn)
            out_path = EXPORTS_DIR / f"dq_{name}.csv"
            df.to_csv(out_path, index=False)
            lines.append(f"- **{name}**: {len(df)} rows exported to `data/exports/dq_{name}.csv`")

    report_path = REPORTS_DIR / "data_quality_report.md"
    report_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Data quality report written to {report_path}")


if __name__ == "__main__":
    main()
