"""
Bronze data-quality audit.

Runs every check in sql/bronze/01_data_quality_checks.sql and compiles the
results into reports/data_quality_report.md, plus CSV samples of offending
rows so the report carries evidence, not just counts.

This is the *descriptive* audit of the raw data. The *enforced* contracts on
silver/gold live in tests/test_data_quality.py and fail the build if broken.
"""

import re

import duckdb
import pandas as pd

from src.config import Settings
from src.db import read_sql_file

DQ_SQL = "bronze/01_data_quality_checks.sql"
ITEM_RE = re.compile(r"^\d+[a-z]\.\s")
SECTION_RE = re.compile(r"^\d+\.\s+[A-Z]")

EVIDENCE_QUERIES = {
    "delivered_before_purchase_sample": """
        SELECT order_id, order_status, order_purchase_timestamp, order_delivered_customer_date
        FROM bronze.orders
        WHERE order_delivered_customer_date::TIMESTAMP < order_purchase_timestamp::TIMESTAMP
        LIMIT 20
    """,
    "carrier_before_approved_sample": """
        SELECT order_id, order_status, order_approved_at, order_delivered_carrier_date
        FROM bronze.orders
        WHERE order_delivered_carrier_date::TIMESTAMP < order_approved_at::TIMESTAMP
        LIMIT 20
    """,
    "delivered_status_missing_delivered_date_sample": """
        SELECT order_id, order_status, order_purchase_timestamp, order_delivered_customer_date
        FROM bronze.orders
        WHERE order_status = 'delivered' AND order_delivered_customer_date IS NULL
        LIMIT 20
    """,
    "delivered_on_estimated_date_sample": """
        SELECT order_id, order_delivered_customer_date, order_estimated_delivery_date
        FROM bronze.orders
        WHERE order_delivered_customer_date::TIMESTAMP::DATE
              = order_estimated_delivery_date::TIMESTAMP::DATE
        LIMIT 20
    """,
}


def parse_statements(sql_text: str) -> list[tuple[str, str]]:
    """Splits the audit file into (label, sql) pairs, labelling each statement
    with the numbered comment ('1a. ...') directly above it."""
    statements, comments, code = [], [], []
    for line in sql_text.splitlines():
        stripped = line.strip()
        if not code and stripped.startswith("--"):
            comments.append(stripped.lstrip("-").strip())
        elif not code and not stripped:
            continue
        elif stripped:
            code.append(line)
            if stripped.endswith(";"):
                items = [c for c in comments if ITEM_RE.match(c)]
                sections = [c for c in comments if SECTION_RE.match(c)]
                label = items[0] if items else (sections[-1] if sections else "Query")
                statements.append((label, "\n".join(code).rstrip(";").strip()))
                comments, code = [], []
    return statements


def render(df: pd.DataFrame) -> str:
    if df.shape == (1, 1):
        return f"**{df.columns[0]}: {df.iloc[0, 0]}**"
    return df.to_markdown(index=False)


def run(con: duckdb.DuckDBPyConnection, settings: Settings) -> int:
    settings.reports_dir.mkdir(parents=True, exist_ok=True)
    settings.exports_dir.mkdir(parents=True, exist_ok=True)

    statements = parse_statements(read_sql_file(DQ_SQL))
    lines = [
        "# Olist Bronze Layer - Data Quality Report",
        "",
        "Generated by `src/quality/data_quality.py` against the `bronze` views "
        "(raw CSVs, every column as text). This is the baseline audit the "
        "silver-layer cleaning rules are derived from.",
        "",
    ]
    for label, sql in statements:
        lines += [f"## {label}", "", render(con.execute(sql).df()), ""]

    lines += ["## Evidence samples", ""]
    for name, sql in EVIDENCE_QUERIES.items():
        df = con.execute(sql).df()
        df.to_csv(settings.exports_dir / f"dq_{name}.csv", index=False)
        lines.append(f"- **{name}**: {len(df)} rows exported to `data/exports/dq_{name}.csv`")

    (settings.reports_dir / "data_quality_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(statements)


def main(settings: Settings | None = None):
    from src.config import get_settings
    from src.db import connect

    settings = settings or get_settings()
    with connect(settings) as con:
        n = run(con, settings)
    print(f"  {n} data-quality checks written to reports/data_quality_report.md")


if __name__ == "__main__":
    main()
